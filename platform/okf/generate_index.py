#!/usr/bin/env python3
"""Write or check the root index.md of every OKF profile 1.0 agent bundle (zuno-demo ADR-0615 clause 3).

The index follows upstream OKF §8 (https://github.com/GoogleCloudPlatform/open-knowledge-format/blob/main/SPEC.md):
- the only frontmatter is `okf_version: "0.2"`;
- the body groups the bundle's documents under headings;
- each document gets a bundle-relative link (`/tasks/<task>.md`) and a one-line description.

It lists exactly what the agent artifact publishes (platform/release/okf_release.py), including the corp skills
the artifact embeds as `skills/corp/<name>.md`. It is generated, never edited by hand. Legacy (v0.2/v0.3)
bundles have no index.

Run from the repository root:
    python3 platform/okf/generate_index.py            # write
    python3 platform/okf/generate_index.py --check    # CI: every profile bundle has an up-to-date index
"""
from __future__ import annotations

import pathlib
import re
import sys
from typing import Dict, List, Optional, Tuple

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "platform" / "okf"))
sys.path.insert(0, str(REPO_ROOT / "platform" / "release"))
from okf_profile import UPSTREAM_OKF_VERSION, UnsupportedVersion, document_version, is_profile  # noqa: E402
import okf_release  # noqa: E402

SECTIONS = (  # (directory, heading); the agent document comes first, tasks keep their declared order
    ("tasks", "Tasks"),
    ("prompts", "Prompts"),
    ("skills", "Skills"),
    ("tools", "Tools"),
    ("rag", "Knowledge"),
    ("policies", "Policies"),
)
MAX_DESCRIPTION = 200


def split(path: pathlib.Path) -> Tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end < 0:
        return {}, text
    return (yaml.safe_load(text[4:end]) or {}), text[end + 4:]


def one_line(front: dict, body: str) -> str:
    """The document's `description`, else the first sentence of its first prose paragraph."""
    text = front.get("description")
    if not isinstance(text, str) or not text.strip():
        text = ""
        for block in re.split(r"\n\s*\n", body):
            block = block.strip()
            if block and not block.startswith(("#", "<!--", "|", "```", "-", "*")):
                text = block
                break
    text = " ".join(text.split())
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    if match:
        text = match.group(1)
    if len(text) > MAX_DESCRIPTION:
        text = text[:MAX_DESCRIPTION - 1].rstrip() + "…"
    return text


def entry(rel: str, path: pathlib.Path) -> str:
    front, body = split(path)
    title = front.get("title") or pathlib.PurePosixPath(rel).stem
    desc = one_line(front, body)
    return f"- [{title}](/{rel})" + (f" - {desc}" if desc else "")


def render(agent_dir: pathlib.Path) -> str:
    agent_front, agent_body = split(agent_dir / "agent.okf.md")
    published: Dict[str, pathlib.Path] = {
        p.relative_to(agent_dir).as_posix(): p
        for p in okf_release.runtime_files(agent_dir) if p.name != "index.md" and p.suffix == ".md"}
    published.update({rel: p for rel, p in okf_release.corp_skills(agent_dir).items()})
    tasks: List[str] = list((agent_front.get("zuno") or {}).get("tasks") or [])
    lines = ["---", f'okf_version: "{UPSTREAM_OKF_VERSION}"', "---", "",
             f"# {agent_front.get('title', agent_dir.name)}", ""]
    summary = one_line(agent_front, agent_body)
    if summary:
        lines += [summary, ""]
    lines += ["Generated by platform/okf/generate_index.py: do not edit.", "", "## Agent", "",
              entry("agent.okf.md", agent_dir / "agent.okf.md"), ""]
    for directory, heading in SECTIONS:
        rels = [r for r in published if r.startswith(f"{directory}/")]
        if not rels:
            continue
        if directory == "tasks":
            order = {f"tasks/{t}.md": i for i, t in enumerate(tasks)}
            rels.sort(key=lambda r: (order.get(r, len(order)), r))
        else:
            rels.sort()
        lines += [f"## {heading}", ""] + [entry(r, published[r]) for r in rels] + [""]
    return "\n".join(lines).rstrip("\n") + "\n"


def profile_bundles() -> List[pathlib.Path]:
    out = []
    for agent_dir in okf_release.agent_dirs():
        try:
            version = document_version(split(agent_dir / "agent.okf.md")[0])
        except UnsupportedVersion:
            continue  # reported by validate_okf_schema.py
        if is_profile(version):
            out.append(agent_dir)
    return out


def main(argv: List[str]) -> int:
    import argparse
    parser = argparse.ArgumentParser(description="Write or check the root index.md of every profile 1.0 bundle.")
    parser.add_argument("--check", action="store_true", help="fail when an index.md is missing or stale; write nothing")
    check = parser.parse_args(argv).check
    problems: List[str] = []
    bundles = profile_bundles()
    for agent_dir in bundles:
        target = agent_dir / "index.md"
        text = render(agent_dir)
        rel = target.relative_to(REPO_ROOT).as_posix()
        if check:
            if not target.is_file():
                problems.append(f"{rel} is missing")
            elif target.read_text(encoding="utf-8") != text:
                problems.append(f"{rel} is stale")
        else:
            target.write_text(text, encoding="utf-8")
    if problems:
        print("\n".join(f"  ✗ {p}" for p in problems))
        print("\nRESULT: FAIL - run python3 platform/okf/generate_index.py and commit the result.")
        return 1
    verb = "match their generator" if check else "written"
    print(f"\nRESULT: PASS - {len(bundles)} profile bundle index(es) {verb}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
